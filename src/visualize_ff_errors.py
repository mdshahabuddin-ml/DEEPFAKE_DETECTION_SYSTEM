"""
src/visualize_ff_errors.py

Visualize the most important FaceForensics++ errors produced by
analyze_ff_errors.py.

Input:
    results/ff_errors/predictions.csv

Output:
    results/ff_errors/visualizations/
        false_positives/
        false_negatives/
        false_positive_montage.jpg
        false_negative_montage.jpg
        selected_errors.csv

Usage:
    python src/visualize_ff_errors.py
"""

from pathlib import Path
import shutil
import math

import cv2
import pandas as pd
import matplotlib.pyplot as plt


# ============================================================
# CONFIGURATION
# ============================================================

PROJECT_ROOT = Path(__file__).resolve().parent.parent

PREDICTIONS_FILE = (
    PROJECT_ROOT
    / "results"
    / "ff_errors"
    / "predictions.csv"
)

OUTPUT_DIR = (
    PROJECT_ROOT
    / "results"
    / "ff_errors"
    / "visualizations"
)

FALSE_POSITIVE_DIR = OUTPUT_DIR / "false_positives"
FALSE_NEGATIVE_DIR = OUTPUT_DIR / "false_negatives"

# Number of errors to visualize
TOP_N = 20

# Number of columns in montage
MONTAGE_COLUMNS = 5

# Image size in montage
IMAGE_SIZE = 224


# ============================================================
# DIRECTORY SETUP
# ============================================================

def create_directories():
    """Create output directories."""

    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    FALSE_POSITIVE_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    FALSE_NEGATIVE_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )


# ============================================================
# LOAD PREDICTIONS
# ============================================================

def load_predictions():
    """Load prediction CSV generated by analyze_ff_errors.py."""

    print("=" * 60)
    print("LOADING FF++ ERROR PREDICTIONS")
    print("=" * 60)

    if not PREDICTIONS_FILE.exists():
        raise FileNotFoundError(
            f"Predictions file not found:\n{PREDICTIONS_FILE}\n\n"
            "Run this first:\n"
            "python src\\analyze_ff_errors.py"
        )

    df = pd.read_csv(PREDICTIONS_FILE)

    required_columns = {
        "path",
        "true_label",
        "prediction",
        "probability_fake",
    }

    missing = required_columns - set(df.columns)

    if missing:
        raise ValueError(
            f"Missing required columns: {sorted(missing)}"
        )

    print(f"Prediction file: {PREDICTIONS_FILE}")
    print(f"Total predictions: {len(df)}")

    return df


# ============================================================
# IDENTIFY ERRORS
# ============================================================

def get_errors(df):
    """Separate false positives and false negatives."""

    false_positives = df[
        (df["true_label"] == 0)
        & (df["prediction"] == 1)
    ].copy()

    false_negatives = df[
        (df["true_label"] == 1)
        & (df["prediction"] == 0)
    ].copy()

    print()
    print("Error counts:")
    print(f"  False positives: {len(false_positives)}")
    print(f"  False negatives: {len(false_negatives)}")

    return false_positives, false_negatives


# ============================================================
# SELECT MOST IMPORTANT ERRORS
# ============================================================

def select_top_errors(
    false_positives,
    false_negatives,
    top_n=TOP_N,
):
    """
    Select the highest-confidence errors.

    False positive:
        Higher probability_fake means stronger incorrect
        confidence that a REAL image is FAKE.

    False negative:
        Lower probability_fake means stronger incorrect
        confidence that a FAKE image is REAL.
    """

    # --------------------------------------------------------
    # False positives
    # --------------------------------------------------------

    fp = false_positives.sort_values(
        by="probability_fake",
        ascending=False,
    ).head(top_n).copy()

    # --------------------------------------------------------
    # False negatives
    # --------------------------------------------------------

    fn = false_negatives.sort_values(
        by="probability_fake",
        ascending=True,
    ).head(top_n).copy()

    return fp, fn


# ============================================================
# COPY ERROR IMAGES
# ============================================================

def copy_error_images(
    dataframe,
    destination,
    error_type,
):
    """
    Copy selected error images to an easy-to-inspect folder.
    """

    copied_records = []

    print()
    print("=" * 60)
    print(f"COPYING {error_type.upper()} IMAGES")
    print("=" * 60)

    for index, row in dataframe.iterrows():

        source = Path(row["path"])

        if not source.exists():
            print(
                f"[WARNING] Image not found:\n"
                f"  {source}"
            )
            continue

        # Make filename unique and informative.
        probability = float(
            row["probability_fake"]
        )

        filename = (
            f"{error_type.lower()}_"
            f"{index:05d}_"
            f"p{probability:.4f}_"
            f"{source.name}"
        )

        destination_file = (
            destination / filename
        )

        try:
            shutil.copy2(
                source,
                destination_file,
            )

            copied_records.append(
                {
                    "error_type": error_type,
                    "original_path": str(source),
                    "visualized_path": str(
                        destination_file
                    ),
                    "true_label": int(
                        row["true_label"]
                    ),
                    "prediction": int(
                        row["prediction"]
                    ),
                    "probability_fake": probability,
                }
            )

        except Exception as exc:
            print(
                f"[WARNING] Could not copy {source}: {exc}"
            )

    print(
        f"Copied {len(copied_records)} "
        f"{error_type} images."
    )

    return copied_records


# ============================================================
# LOAD IMAGE FOR MONTAGE
# ============================================================

def load_image(path):
    """Read image and convert BGR -> RGB."""

    image = cv2.imread(str(path))

    if image is None:
        return None

    image = cv2.cvtColor(
        image,
        cv2.COLOR_BGR2RGB,
    )

    return image


# ============================================================
# CREATE MONTAGE
# ============================================================

def create_montage(
    dataframe,
    output_file,
    title,
    top_n=TOP_N,
):
    """
    Create a matplotlib montage of selected errors.
    """

    dataframe = dataframe.head(top_n)

    if len(dataframe) == 0:
        print(
            f"[WARNING] No images available for {title}"
        )
        return

    rows = math.ceil(
        len(dataframe) / MONTAGE_COLUMNS
    )

    fig, axes = plt.subplots(
        rows,
        MONTAGE_COLUMNS,
        figsize=(
            MONTAGE_COLUMNS * 3.2,
            rows * 3.2,
        ),
    )

    # Normalize axes to a flat list.
    if hasattr(axes, "flat"):
        axes = list(axes.flat)
    else:
        axes = [axes]

    for ax in axes:
        ax.axis("off")

    for position, (_, row) in enumerate(
        dataframe.iterrows()
    ):

        ax = axes[position]

        image_path = Path(
            row["path"]
        )

        image = load_image(
            image_path
        )

        if image is None:
            ax.text(
                0.5,
                0.5,
                "Image\nnot found",
                ha="center",
                va="center",
            )
            ax.axis("off")
            continue

        ax.imshow(image)

        probability = float(
            row["probability_fake"]
        )

        filename = image_path.name

        # Shorten long filenames.
        if len(filename) > 28:
            filename = (
                filename[:25] + "..."
            )

        ax.set_title(
            f"p(fake)={probability:.3f}\n"
            f"{filename}",
            fontsize=8,
        )

        ax.axis("off")

    fig.suptitle(
        title,
        fontsize=16,
    )

    plt.tight_layout(
        rect=[0, 0, 1, 0.95]
    )

    fig.savefig(
        output_file,
        dpi=200,
        bbox_inches="tight",
    )

    plt.close(fig)

    print(
        f"Saved montage:\n"
        f"  {output_file}"
    )


# ============================================================
# CREATE CSV SUMMARY
# ============================================================

def save_selected_errors(
    fp,
    fn,
):
    """Save selected errors into one CSV."""

    fp_save = fp.copy()
    fn_save = fn.copy()

    fp_save["error_type"] = (
        "FALSE_POSITIVE"
    )

    fn_save["error_type"] = (
        "FALSE_NEGATIVE"
    )

    selected = pd.concat(
        [
            fp_save,
            fn_save,
        ],
        ignore_index=True,
    )

    output_file = (
        OUTPUT_DIR
        / "selected_errors.csv"
    )

    selected.to_csv(
        output_file,
        index=False,
    )

    print(
        f"Saved selected error CSV:\n"
        f"  {output_file}"
    )


# ============================================================
# PRINT SUMMARY
# ============================================================

def print_summary(
    false_positives,
    false_negatives,
    selected_fp,
    selected_fn,
):
    """Print useful error-analysis statistics."""

    print()
    print("=" * 60)
    print("ERROR VISUALIZATION SUMMARY")
    print("=" * 60)

    print(
        f"Total false positives: "
        f"{len(false_positives)}"
    )

    print(
        f"Total false negatives: "
        f"{len(false_negatives)}"
    )

    if len(false_positives) > 0:

        print(
            "\nFalse-positive confidence:"
        )

        print(
            f"  Mean: "
            f"{false_positives['probability_fake'].mean():.4f}"
        )

        print(
            f"  Max : "
            f"{false_positives['probability_fake'].max():.4f}"
        )

        print(
            f"  Min : "
            f"{false_positives['probability_fake'].min():.4f}"
        )

    if len(false_negatives) > 0:

        print(
            "\nFalse-negative confidence:"
        )

        print(
            f"  Mean: "
            f"{false_negatives['probability_fake'].mean():.4f}"
        )

        print(
            f"  Max : "
            f"{false_negatives['probability_fake'].max():.4f}"
        )

        print(
            f"  Min : "
            f"{false_negatives['probability_fake'].min():.4f}"
        )

    print()
    print(
        f"Selected false positives: "
        f"{len(selected_fp)}"
    )

    print(
        f"Selected false negatives: "
        f"{len(selected_fn)}"
    )

    print("=" * 60)


# ============================================================
# MAIN
# ============================================================

def main():

    print("=" * 60)
    print("FACEFORENSICS++ ERROR VISUALIZATION")
    print("=" * 60)

    print(
        f"Top errors to visualize: {TOP_N}"
    )

    print(
        f"Predictions file:\n"
        f"{PREDICTIONS_FILE}"
    )

    print(
        f"Output directory:\n"
        f"{OUTPUT_DIR}"
    )

    # --------------------------------------------------------
    # Create directories
    # --------------------------------------------------------

    create_directories()

    # --------------------------------------------------------
    # Load predictions
    # --------------------------------------------------------

    df = load_predictions()

    # --------------------------------------------------------
    # Find errors
    # --------------------------------------------------------

    false_positives, false_negatives = (
        get_errors(df)
    )

    # --------------------------------------------------------
    # Select highest-confidence errors
    # --------------------------------------------------------

    selected_fp, selected_fn = (
        select_top_errors(
            false_positives,
            false_negatives,
            TOP_N,
        )
    )

    print()
    print(
        "Selected highest-confidence errors:"
    )

    print(
        f"  False positives: "
        f"{len(selected_fp)}"
    )

    print(
        f"  False negatives: "
        f"{len(selected_fn)}"
    )

    # --------------------------------------------------------
    # Copy images
    # --------------------------------------------------------

    fp_records = copy_error_images(
        selected_fp,
        FALSE_POSITIVE_DIR,
        "FALSE_POSITIVE",
    )

    fn_records = copy_error_images(
        selected_fn,
        FALSE_NEGATIVE_DIR,
        "FALSE_NEGATIVE",
    )

    # --------------------------------------------------------
    # Save selected CSV
    # --------------------------------------------------------

    save_selected_errors(
        selected_fp,
        selected_fn,
    )

    # --------------------------------------------------------
    # Create montages
    # --------------------------------------------------------

    fp_montage = (
        OUTPUT_DIR
        / "false_positive_montage.jpg"
    )

    fn_montage = (
        OUTPUT_DIR
        / "false_negative_montage.jpg"
    )

    create_montage(
        selected_fp,
        fp_montage,
        "Top False Positives - FaceForensics++",
        TOP_N,
    )

    create_montage(
        selected_fn,
        fn_montage,
        "Top False Negatives - FaceForensics++",
        TOP_N,
    )

    # --------------------------------------------------------
    # Print summary
    # --------------------------------------------------------

    print_summary(
        false_positives,
        false_negatives,
        selected_fp,
        selected_fn,
    )

    # --------------------------------------------------------
    # Final output
    # --------------------------------------------------------

    print()
    print("=" * 60)
    print("VISUALIZATION COMPLETED")
    print("=" * 60)

    print(
        "\nOpen these files:"
    )

    print(
        f"  False-positive montage:\n"
        f"  {fp_montage}"
    )

    print(
        f"\n  False-negative montage:\n"
        f"  {fn_montage}"
    )

    print(
        f"\n  Selected errors CSV:\n"
        f"  {OUTPUT_DIR / 'selected_errors.csv'}"
    )

    print(
        f"\n  Individual false positives:\n"
        f"  {FALSE_POSITIVE_DIR}"
    )

    print(
        f"\n  Individual false negatives:\n"
        f"  {FALSE_NEGATIVE_DIR}"
    )

    print("=" * 60)


# ============================================================
# ENTRY POINT
# ============================================================

if __name__ == "__main__":
    main()